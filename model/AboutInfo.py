def maintenance_lessons_text():
    lines = ["已确认的维护复盘（保留，不粉饰）", ""]
    for index, lesson in enumerate(MAINTENANCE_LESSONS, 1):
        lines.extend(
            (
                f"{index}. {lesson['title']}",
                f"   错误：{lesson['mistake']}",
                f"   以后必须遵守：{lesson['rule']}",
                "",
            )
        )
    return "\n".join(lines).rstrip()
